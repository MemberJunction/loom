import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import type { DomainConfig } from '@memberjunction/loom-contracts';

export interface SkywayMigrationOptions {
  outputDir: string;
  version: string;
  description: string;
  domain: DomainConfig;
  data: Record<string, readonly Record<string, unknown>[]>;
  statusTransitions?: readonly {
    entity: string;
    id: string;
    fromStatus: string;
    toStatus: string;
    effectiveDate: string;
  }[];
  dialect?: 'sqlserver' | 'postgres';
  useSpCreate?: boolean;
}

/**
 * Emits additive Skyway migrations with dual-dialect support (SQL Server & PostgreSQL).
 * 1. Topologically sorts entities (parents before children) so foreign keys never fail at apply-time.
 * 2. Validates all emitted columns strictly against domain entity field declarations.
 * 3. Escapes JSON objects and strings cleanly, avoiding [object Object] leaks.
 * 4. Deterministically sorts records by primary key for 100% byte-for-byte idempotency.
 */
export async function emitSkywayMigration(options: SkywayMigrationOptions): Promise<string> {
  await fs.mkdir(options.outputDir, { recursive: true });

  const dialect = options.dialect ?? 'sqlserver';
  const isPostgres = dialect === 'postgres';
  const safeDesc = options.description.replace(/[^a-zA-Z0-9_]/g, '_');
  const fileName = `V${options.version}__${safeDesc}.sql`;
  const filePath = path.join(options.outputDir, fileName);

  const lines: string[] = [
    `-- =============================================================================`,
    `-- Migration: ${fileName}`,
    `-- Generated by Loom Simulation Engine (MemberJunction)`,
    `-- Target Dialect: ${dialect}`,
    `-- =============================================================================`,
    ``,
    isPostgres ? `BEGIN;` : `BEGIN TRANSACTION;`,
    ``,
  ];

  // Topologically sort entity emission order: parents before children
  const entityNames = Object.keys(options.data);
  const orderedEntities = sortEntitiesTopologically(entityNames, options.domain);

  for (const entityName of orderedEntities) {
    const rawRecords = options.data[entityName] ?? [];
    if (rawRecords.length === 0) continue;

    const entityCfg = options.domain.entities[entityName];
    if (!entityCfg) {
      throw new Error(`emitSkywayMigration: entity '${entityName}' is not defined in domain configuration`);
    }

    const schemaName = entityCfg.schema ?? 'dbo';
    const tableName = entityCfg.targetTable ?? entityName;
    const declaredFields = new Set(Object.keys(entityCfg.fields));

    // Allow primary key field
    declaredFields.add('ID');
    declaredFields.add('id');

    const fullTableName = isPostgres
      ? `"${schemaName}"."${tableName}"`
      : `[${schemaName}].[${tableName}]`;

    // Sort records deterministically by primary key (ID) using code-point comparison
    const records = [...rawRecords].sort((a, b) => {
      const idA = String(a['ID'] ?? a['id'] ?? '');
      const idB = String(b['ID'] ?? b['id'] ?? '');
      return idA < idB ? -1 : idA > idB ? 1 : 0;
    });

    lines.push(`-- Entity: ${entityName} (${records.length} records)`);

    for (const record of records) {
      const cols = Object.keys(record);

      // Strictly validate that all columns exist in domain configuration
      for (const col of cols) {
        if (!declaredFields.has(col)) {
          throw new Error(
            `emitSkywayMigration: undeclared column '${col}' in entity '${entityName}'. Emitted columns must be declared in domain.json.`
          );
        }
      }

      const colList = isPostgres
        ? cols.map((c) => `"${c}"`).join(', ')
        : cols.map((c) => `[${c}]`).join(', ');

      const valList = cols.map((c) => formatSqlValue(record[c], isPostgres)).join(', ');

      if (options.useSpCreate) {
        if (isPostgres) {
          // PostgreSQL procedure call: CALL "schema"."spCreate"(...)
          lines.push(`CALL "${schemaName}"."spCreate${tableName}"(${valList});`);
        } else {
          // SQL Server stored procedure call: EXEC [schema].[spCreate...] @col = val
          const paramList = cols
            .map((c) => `@${c} = ${formatSqlValue(record[c], isPostgres)}`)
            .join(', ');
          lines.push(`EXEC [${schemaName}].[spCreate${tableName}] ${paramList};`);
        }
      } else {
        // Direct transactional SQL insert
        lines.push(`INSERT INTO ${fullTableName} (${colList}) VALUES (${valList});`);
      }
    }
    lines.push(``);
  }

  // Emit status transitions as updates
  if (options.statusTransitions && options.statusTransitions.length > 0) {
    lines.push(`-- Status Transitions`);
    for (const tr of options.statusTransitions) {
      const entityCfg = options.domain.entities[tr.entity];
      if (!entityCfg) continue;
      const schemaName = entityCfg.schema ?? 'dbo';
      const tableName = entityCfg.targetTable ?? tr.entity;
      const fullTableName = isPostgres ? `"${schemaName}"."${tableName}"` : `[${schemaName}].[${tableName}]`;
      const statusCol = isPostgres ? `"Status"` : `[Status]`;
      const idCol = isPostgres ? `"ID"` : `[ID]`;
      const statusVal = formatSqlValue(tr.toStatus, isPostgres);
      const idVal = formatSqlValue(tr.id, isPostgres);
      lines.push(`UPDATE ${fullTableName} SET ${statusCol} = ${statusVal} WHERE ${idCol} = ${idVal};`);
    }
    lines.push(``);
  }

  lines.push(isPostgres ? `COMMIT;` : `COMMIT TRANSACTION;`);
  lines.push(``);

  await fs.writeFile(filePath, lines.join('\n'), 'utf8');
  return filePath;
}

/**
 * Topologically sorts entity names so that parent entities precede child entities
 * in generated SQL insertion statements.
 * Throws if a cyclic foreign key dependency is detected.
 */
export function sortEntitiesTopologically(
  entityNames: string[],
  domain: DomainConfig
): string[] {
  const set = new Set(entityNames);
  const inDegree = new Map<string, number>();
  const adj = new Map<string, Set<string>>();

  for (const name of entityNames) {
    inDegree.set(name, 0);
    adj.set(name, new Set());
  }

  for (const name of entityNames) {
    const entityCfg = domain.entities[name];
    if (!entityCfg || !entityCfg.foreignKeys) continue;

    for (const fk of Object.values(entityCfg.foreignKeys)) {
      const parent = fk.targetEntity;
      if (set.has(parent) && parent !== name) {
        // parent -> name (parent must precede child)
        const children = adj.get(parent)!;
        if (!children.has(name)) {
          children.add(name);
          inDegree.set(name, inDegree.get(name)! + 1);
        }
      }
    }
  }

  // Seed Kahn queue in deterministic code-point order
  const zeroInDegree = entityNames
    .filter((name) => inDegree.get(name) === 0)
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

  const queue: string[] = [...zeroInDegree];
  const sorted: string[] = [];

  while (queue.length > 0) {
    const curr = queue.shift()!;
    sorted.push(curr);

    const children = Array.from(adj.get(curr) ?? []).sort((a, b) =>
      a < b ? -1 : a > b ? 1 : 0
    );
    for (const child of children) {
      const newDeg = inDegree.get(child)! - 1;
      inDegree.set(child, newDeg);
      if (newDeg === 0) queue.push(child);
    }
  }

  if (sorted.length !== entityNames.length) {
    const sortedSet = new Set(sorted);
    const unresolved = entityNames
      .filter((name) => !sortedSet.has(name))
      .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
    throw new Error(
      `Cyclic foreign key dependency detected among entities: ${unresolved.join(', ')}`
    );
  }

  return sorted;
}

function formatSqlValue(val: unknown, isPostgres: boolean): string {
  if (val === null || val === undefined) return 'NULL';
  if (typeof val === 'number') return String(val);
  if (typeof val === 'boolean') return isPostgres ? (val ? 'TRUE' : 'FALSE') : val ? '1' : '0';

  if (typeof val === 'object') {
    const jsonStr = JSON.stringify(val).replace(/'/g, "''");
    return `'${jsonStr}'`;
  }

  const str = String(val).replace(/'/g, "''");
  return `'${str}'`;
}
